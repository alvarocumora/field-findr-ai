CREATE OR REPLACE FUNCTION public.get_public_sales_quote(p_token uuid)
RETURNS TABLE(quote_number bigint, project_name text, lot_label text, lot_area numeric, customer_name text, currency text, list_price numeric, discount_amount numeric, quoted_price numeric, valid_until timestamptz, status text, notes text)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT q.quote_number, q.project_name_snapshot, q.lot_label_snapshot, q.lot_area_snapshot, q.customer_name, q.currency, q.list_price, q.discount_amount, q.quoted_price, q.valid_until,
    CASE WHEN q.valid_until < now() AND q.status NOT IN ('accepted','rejected','cancelled') THEN 'expired' ELSE q.status END, q.notes
  FROM public.sales_quotes q WHERE q.public_token = p_token AND q.status <> 'draft' LIMIT 1;
$$;
CREATE OR REPLACE FUNCTION public.track_sales_quote_view(p_token uuid) RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_quote_id uuid;
BEGIN
  UPDATE public.sales_quotes SET status = CASE WHEN status = 'sent' THEN 'viewed' ELSE status END, updated_at = now()
  WHERE public_token = p_token AND status IN ('sent','viewed') RETURNING id INTO v_quote_id;
  IF v_quote_id IS NULL THEN RETURN false; END IF;
  INSERT INTO public.sales_quote_events(quote_id, event_type, channel)
  SELECT v_quote_id, 'viewed', 'public_link'
  WHERE NOT EXISTS (SELECT 1 FROM public.sales_quote_events WHERE quote_id = v_quote_id AND event_type = 'viewed' AND created_at > now() - interval '30 minutes');
  RETURN true;
END; $$;
REVOKE ALL ON FUNCTION public.get_public_sales_quote(uuid) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.track_sales_quote_view(uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.get_public_sales_quote(uuid) TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.track_sales_quote_view(uuid) TO anon, authenticated;
CREATE OR REPLACE FUNCTION public.capture_sales_quote_snapshot() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  SELECT p.name, COALESCE(l.name, 'Lote ' || l.lot_number::text), l.area
  INTO NEW.project_name_snapshot, NEW.lot_label_snapshot, NEW.lot_area_snapshot
  FROM public.projects p JOIN public.lots l ON l.project_id = p.id
  WHERE p.id = NEW.project_id AND l.id = NEW.lot_id;
  RETURN NEW;
END; $$;
DROP TRIGGER IF EXISTS trg_capture_sales_quote_snapshot ON public.sales_quotes;
CREATE TRIGGER trg_capture_sales_quote_snapshot BEFORE INSERT ON public.sales_quotes FOR EACH ROW EXECUTE FUNCTION public.capture_sales_quote_snapshot();

