CREATE OR REPLACE FUNCTION public.can_access_project(_project_id uuid, _capability text DEFAULT 'projects.read', _user_id uuid DEFAULT auth.uid())
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (SELECT 1 FROM public.projects AS project WHERE project.id = _project_id AND (
    project.user_id = _user_id
    OR (project.organization_id IS NOT NULL AND public.organization_has_capability(project.organization_id, _capability, _user_id))
    OR EXISTS (SELECT 1 FROM public.project_members WHERE project_id = _project_id AND user_id = _user_id)));
$$;
GRANT EXECUTE ON FUNCTION public.can_access_project(uuid, text, uuid) TO authenticated, service_role;