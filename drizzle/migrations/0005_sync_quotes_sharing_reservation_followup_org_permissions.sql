CREATE OR REPLACE FUNCTION public.organization_role(_organization_id uuid, _user_id uuid DEFAULT auth.uid())
RETURNS text LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT CASE WHEN EXISTS (SELECT 1 FROM public.organizations WHERE id = _organization_id AND owner_id = _user_id) THEN 'owner'
    ELSE (SELECT role FROM public.organization_members WHERE organization_id = _organization_id AND user_id = _user_id LIMIT 1) END;
$$;
CREATE OR REPLACE FUNCTION public.organization_has_capability(_organization_id uuid, _capability text, _user_id uuid DEFAULT auth.uid())
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT CASE public.organization_role(_organization_id, _user_id)
    WHEN 'owner' THEN true WHEN 'admin' THEN true WHEN 'org_admin' THEN true
    WHEN 'commercial_manager' THEN _capability = ANY (ARRAY['projects.read','projects.write','inventory.read','inventory.write','crm.read','crm.write','reservations.read','reservations.write','sales.read','reports.read','team.read'])
    WHEN 'sales_agent' THEN _capability = ANY (ARRAY['projects.read','inventory.read','crm.read','crm.write','reservations.read','reservations.write','sales.read','commissions.read'])
    WHEN 'member' THEN _capability = ANY (ARRAY['projects.read','inventory.read','crm.read','crm.write','reservations.read','reservations.write','sales.read','commissions.read'])
    WHEN 'operations' THEN _capability = ANY (ARRAY['projects.read','projects.write','inventory.read','inventory.write','reservations.read','reservations.write','documents.read','documents.write'])
    WHEN 'finance' THEN _capability = ANY (ARRAY['sales.read','payments.read','payments.write','commissions.read','commissions.write','reports.read'])
    WHEN 'viewer' THEN _capability = ANY (ARRAY['projects.read','inventory.read','crm.read','reservations.read','sales.read','payments.read','commissions.read','reports.read','team.read'])
    ELSE false END;
$$;
GRANT EXECUTE ON FUNCTION public.organization_role(uuid, uuid) TO authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.organization_has_capability(uuid, text, uuid) TO authenticated, service_role;
